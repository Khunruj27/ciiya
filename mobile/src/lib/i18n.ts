export type { Locale } from '@/lib/language-preference';

export function getDeviceLocale(): Locale {
  const language = getLocales()[0]?.languageCode;
  return resolveLocale('system', language);
}

const dictionaries: Record<Locale, Dictionary> = { th, en };

export function getDictionary(locale: Locale = getDeviceLocale()): Dictionary {
  return dictionaries[locale];
}

export function useLocale(): Locale {
  const language = useLanguage();
  return language?.locale ?? getDeviceLocale();
}

/** React context updates subscribed screens without changing route keys. */
export function useT(): Dictionary {
  return getDictionary(useLocale());
}

